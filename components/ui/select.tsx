"use client"

import * as React from "react"
import { Select as SelectPrimitive } from "@base-ui/react/select"

import { cn } from "@/lib/utils"
// HugeIcons rather than the lucide set shadcn generates: the house rule is one
// icon family, stroke-rounded, and every other component on the estate page
// already draws from this one.
import { ArrowDown01Icon, ArrowUp01Icon, Tick02Icon } from "@hugeicons/core-free-icons"
import { HugeiconsIcon } from "@hugeicons/react"

const Select = SelectPrimitive.Root

