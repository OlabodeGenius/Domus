// Two additions to what shadcn generates, both for the dropdown panel the
// estate search draws from: `indicator` moves the tick to the row's leading
// edge, where that reference puts an icon, and `trailing` renders outside
// ItemText — anything inside it is cloned into the trigger, so a per-row count
// put there would show up beside the chosen value.
//
// The highlight is data-highlighted rather than the registry's focus:. Base UI
// keeps DOM focus on the popup and marks the active row with an attribute, so
// a focus: rule here would never paint.
function SelectItem({
  className,
  children,
  indicator = "end",
  trailing,
  ...props
}: SelectPrimitive.Item.Props & {
  indicator?: "start" | "end"
  trailing?: React.ReactNode
}) {
  return (
    <SelectPrimitive.Item
      data-slot="select-item"
      className={cn(
        "relative flex w-full cursor-default items-center gap-1.5 rounded-md py-1 text-sm outline-hidden select-none data-highlighted:bg-accent data-highlighted:text-accent-foreground not-data-[variant=destructive]:data-highlighted:**:text-accent-foreground data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        indicator === "start" ? "pr-2 pl-8" : "pr-8 pl-1.5",
        className
      )}
      {...props}
    >
      <span
        className={cn(
          "pointer-events-none absolute flex size-4 items-center justify-center",
          indicator === "start" ? "left-2" : "right-2"
        )}
      >
        <SelectPrimitive.ItemIndicator>
          <HugeiconsIcon icon={Tick02Icon} size={16} strokeWidth={1.5} className="pointer-events-none" />
        </SelectPrimitive.ItemIndicator>
      </span>
      <SelectPrimitive.ItemText>{children}</SelectPrimitive.ItemText>
      {trailing}
    </SelectPrimitive.Item>
  )
}

